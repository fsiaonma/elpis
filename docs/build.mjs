/**
 * 将 docs/ 下所有 .md 打包为 docs.bundle.js，供 index.html 直接打开。
 * 版本号取根目录 package.json。
 * 修改 Markdown 后执行：npm run docs:build
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const docsDir = fileURLToPath(new URL('.', import.meta.url));
const rootDir = join(docsDir, '..');

async function collectMarkdownFiles(dir, base = dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...await collectMarkdownFiles(fullPath, base));
      continue;
    }
    if (entry.name.endsWith('.md')) {
      files.push(relative(base, fullPath).split('\\').join('/'));
    }
  }

  return files.sort();
}

const mdFiles = await collectMarkdownFiles(docsDir);
const bundle = {};
const pkg = JSON.parse(await readFile(join(rootDir, 'package.json'), 'utf8'));

for (const file of mdFiles) {
  bundle[file] = await readFile(join(docsDir, file), 'utf8');
}

const output = `// Auto-generated by docs/build.mjs — do not edit manually
// Regenerate: npm run docs:build
window.ELPIS_VERSION = ${JSON.stringify(pkg.version)};
window.DOCS_BUNDLE = ${JSON.stringify(bundle)};
`;

await writeFile(join(docsDir, 'docs.bundle.js'), output, 'utf8');

const indexPath = join(docsDir, 'index.html');
const versionBlock = `<script>window.ELPIS_VERSION=${JSON.stringify(pkg.version)};</script>
  <script src="./docs.bundle.js?v=${pkg.version}"></script>`;
let indexHtml = await readFile(indexPath, 'utf8');
const markerRe = /<!-- @elpis-docs-build version-scripts -->[\s\S]*?<!-- @elpis-docs-build end -->/;

if (!markerRe.test(indexHtml)) {
  throw new Error('index.html 缺少 @elpis-docs-build 标记');
}

indexHtml = indexHtml.replace(
  markerRe,
  `<!-- @elpis-docs-build version-scripts -->\n  ${versionBlock}\n  <!-- @elpis-docs-build end -->`,
);
await writeFile(indexPath, indexHtml, 'utf8');
console.log(`Bundled ${mdFiles.length} markdown files → docs.bundle.js (v${pkg.version})`);
